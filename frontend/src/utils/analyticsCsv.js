import { toCsv } from './csv';
import { SEVERITY_LABEL, inSeverityOrder } from './severity';
import { MEASURES } from '../components/Analytics/measures';

/**
 * The Analytics tab as CSV sections, one table per part of the screen, so the
 * file matches what the officer was looking at. The seasonal outlook and the
 * barangay likelihood are left out: they are drawn from the whole archive,
 * not from this period's figures.
 */
export function analyticsCsv(d) {
  const k = d.kpis;
  const meta = [
    ['Report', 'Analytics'],
    ['Generated by', d.generated_by],
    ['Generated at', new Date(d.generated_at).toLocaleString()],
    ['Period', `Last ${d.months} months, from ${d.since}`],
    ['Hazard type', d.hazard_type?.name || 'All types'],
  ];
  if (d.includes_samples) meta.push(['Note', 'Includes sample data. Not an official record.']);
  const table = (title, rows, key, head, label = (r) => r[key] || 'Unspecified') => ({
    title, header: [head, 'Count'], rows: (rows || []).map((r) => [label(r), r.count]),
  });
  return toCsv([
    { title: 'Summary', header: ['Measure', 'Value'], rows: [
      ['Active hazard zones now', k.active_zones_now],
      ['Hazard zones published', k.zones_published],
      ['Zones withdrawn as published in error', k.zones_retracted],
      ['Alerts issued', k.alerts_issued],
      ['Extreme alerts', k.extreme_alerts],
      ['Alert notices sent', k.notices_sent],
      ['Alert notices read', k.notices_read],
      ['Read rate (%)', k.read_rate === null || k.read_rate === undefined ? '' : Math.round(k.read_rate * 100)],
      ['Median minutes to read', k.median_minutes_to_read],
      ['Incident reports submitted', k.incidents_submitted],
      ['Incident reports pending', k.incidents_pending],
      ['Incident reports validated', k.incidents_validated],
      ['Incident reports rejected', k.incidents_rejected],
      ['Median minutes to review', k.median_minutes_to_review],
      ['Median minutes a zone stayed active', k.median_minutes_zone_active],
      ['Recorded hazard events', k.recorded_events],
    ] },
    {
      title: 'By month',
      header: ['Month', ...MEASURES.map((s) => s.label)],
      rows: d.monthly.map((m) => [m.month, ...MEASURES.map((s) => m[s.key])]),
    },
    table('Zones by hazard type', d.zones_by_type, 'hazard_type__name', 'Hazard type'),
    table('Zones by severity', inSeverityOrder(d.zones_by_severity), 'severity', 'Severity',
      (r) => SEVERITY_LABEL[r.severity] || r.severity),
    {
      title: 'Barangay activity',
      header: ['Barangay', 'Zones', 'Incident reports'],
      rows: (d.barangays || []).map((r) => [r.barangay, r.zones, r.incidents]),
    },
  ], meta);
}
