import { toCsv } from '../../utils/csv';
import { hazardsIn } from './trendShapes';
import {
  MON, STATUS, changeLine, howOften, lastYear, mostCommon, plainSentence, stoodOut,
} from './trendWords';

/**
 * Trend Analysis as CSV: the four sections on screen, in the same words,
 * plus the figures behind the map (area and events per km²). A section
 * whose answer did not load is left out.
 */
export function trendCsv({ trends, patterns, places }, words) {
  const made = trends || patterns || places;
  const meta = [
    ['Report', 'Trend Analysis'],
    ['Filters', words],
    ['Generated by', made?.generated_by || ''],
    ['Generated at', made?.generated_at ? new Date(made.generated_at).toLocaleString() : ''],
  ];
  const sections = [];

  if (patterns) {
    sections.push({
      title: 'At a glance',
      header: ['Hazard', 'Status', 'Events in each full year', 'Last full year', 'Compared with the years before',
        'This year so far', 'In words'],
      rows: patterns.hazards.map((h) => {
        const last = lastYear(h);
        return [h.hazard, STATUS[h.verdict], h.years.map((y) => `${y.year}: ${y.count}`).join('; '),
          last ? `${last.count} in ${last.year}` : '', changeLine(h.change) || '',
          h.so_far ? `${h.so_far.count} (to ${h.so_far.through})` : '', plainSentence(h)];
      }),
    });
    sections.push({
      title: 'Months that stood out', header: ['Month', 'Hazard', 'Events', 'In words'],
      rows: patterns.unusual_months.map((m) => [m.label, m.hazard, m.count, stoodOut(m)]),
    });
  }

  if (trends) {
    const hazards = hazardsIn(trends);
    sections.push({
      title: `Year by year (by ${trends.range.granularity})`, header: ['Period', 'Part of the period', ...hazards, 'Total'],
      rows: trends.series.map((s) => [s.label, s.partial ? 'yes' : '', ...hazards.map((h) => s.counts[h] || 0), s.total]),
    });
    sections.push({
      title: 'Busiest months (average events a year)', header: ['Hazard', ...MON],
      rows: (trends.month_average || []).map((a) => [a.hazard, ...a.months.map((v) => (v === null ? '' : v))]),
    });
  }

  if (places) {
    const fullYears = places.years.filter((y) => y.complete).length;
    const mix = new Map((trends?.barangays || []).map((b) => [b.id, b.counts]));
    sections.push({
      title: 'Where it happens',
      header: ['Barangay', 'Events', 'Most common', 'How often', 'Area (km²)', 'Events per km²'],
      rows: places.barangays.map((b) => [b.name, b.total, b.total ? mostCommon(mix.get(b.id)) : '',
        howOften(b, fullYears), b.area_km2 ?? '', b.per_km2 ?? '']),
    });
  }
  return toCsv(sections, meta);
}
