import React, { useEffect, useMemo, useState } from 'react';
import TrendLine from '../components/Charts/TrendLine';
import CategoryBars from '../components/Charts/CategoryBars';
import BarangayLikelihood from '../components/Forecast/BarangayLikelihood';
import { hazardSeriesColor, severitySeriesColor, SEVERITY_LABEL, INK } from '../components/Charts/chartTheme';
import { reportsApi } from '../api/reportApi';
import { toCsv, downloadCsv, csvFilename } from '../utils/csv';
import './css/Dashboard.css';
import './css/Analytics.css';

const WINDOWS = [3, 6, 12, 24];

// The month-by-month series, and the colour each is drawn in
const SERIES = [
  { key: 'zones', label: 'Hazard zones published', color: INK.navy },
  { key: 'alerts', label: 'Alerts issued', color: '#c2410c' },
  { key: 'incidents', label: 'Incident reports', color: '#0f766e' },
  { key: 'events', label: 'Recorded hazard events', color: '#6d28d9' },
];

const MONTH_SHORT = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const monthLabel = (ym) => {
  const [y, m] = ym.split('-').map(Number);
  return `${MONTH_SHORT[m - 1]} ${y}`;
};

/** 95 minutes -> "1 h 35 min"; 3000 -> "2.1 days" */
export function duration(minutes) {
  if (minutes === null || minutes === undefined) return '—';
  if (minutes < 60) return `${Math.round(minutes)} min`;
  if (minutes < 48 * 60) {
    const h = Math.floor(minutes / 60);
    const m = Math.round(minutes % 60);
    return m ? `${h} h ${m} min` : `${h} h`;
  }
  return `${(minutes / 1440).toFixed(1)} days`;
}

const percent = (x) => (x === null || x === undefined ? '—' : `${Math.round(x * 100)}%`);

const toRows = (rows, key, label = (r) => r[key] || 'Unspecified', color) =>
  (rows || []).map((r) => ({ label: label(r), value: r.count, color: color ? color(r) : undefined }));

function Stat({ value, label, hint }) {
  return (
    <div className="db-stat">
      <div className="db-stat-value">{value ?? '—'}</div>
      <div className="db-stat-label">{label}</div>
      {hint && <div className="an-stat-hint">{hint}</div>}
    </div>
  );
}

function analyticsCsv(d) {
  const k = d.kpis;
  const meta = [
    ['Report', 'Analytics'],
    ['Generated by', d.generated_by],
    ['Generated at', new Date(d.generated_at).toLocaleString()],
    ['Period', `Last ${d.months} months, from ${d.since}`],
  ];
  if (d.includes_samples) meta.push(['Note', 'Includes sample data. Not an official record.']);
  const table = (title, rows, key, head, label = (r) => r[key] || 'Unspecified') => ({
    title, header: [head, 'Count'], rows: (rows || []).map((r) => [label(r), r.count]),
  });
  return toCsv([
    { title: 'Summary', header: ['Measure', 'Value'], rows: [
      ['Active hazard zones now', k.active_zones_now],
      ['Hazard zones published', k.zones_published],
      ['Zones withdrawn as published in error', k.zones_retracted],
      ['Alerts issued', k.alerts_issued],
      ['Extreme alerts', k.extreme_alerts],
      ['Alert notices sent', k.notices_sent],
      ['Alert notices read', k.notices_read],
      ['Read rate (%)', k.read_rate === null ? '' : Math.round(k.read_rate * 100)],
      ['Median minutes to read', k.median_minutes_to_read],
      ['Incident reports submitted', k.incidents_submitted],
      ['Incident reports pending', k.incidents_pending],
      ['Incident reports validated', k.incidents_validated],
      ['Incident reports rejected', k.incidents_rejected],
      ['Median minutes to review', k.median_minutes_to_review],
      ['Median minutes a zone stayed active', k.median_minutes_zone_active],
      ['Recorded hazard events', k.recorded_events],
    ] },
    {
      title: 'By month',
      header: ['Month', ...SERIES.map((s) => s.label)],
      rows: d.monthly.map((m) => [m.month, ...SERIES.map((s) => m[s.key])]),
    },
    table('Zones by hazard type', d.zones_by_type, 'hazard_type__name', 'Hazard type'),
    table('Zones by severity', d.zones_by_severity, 'severity', 'Severity', (r) => SEVERITY_LABEL[r.severity] || r.severity),
    table('Zones by barangay (top 10)', d.zones_by_barangay, 'barangay__name', 'Barangay'),
    table('Incident reports by barangay (top 10)', d.incidents_by_barangay, 'barangay__name', 'Barangay'),
  ], meta);
}

/**
 * F7 Analytics dashboard. How the office has been responding, month by
 * month: zones published, alerts issued and read, incident reports and how
 * fast they are reviewed, with the seasonal outlook for next month. It can
 * be downloaded as CSV, saved as PDF or printed, and each of those is
 * written to the audit log.
 */
export default function AnalyticsPanel() {
  const [months, setMonths] = useState(12);
  const [includeSamples, setIncludeSamples] = useState(false);
  const [series, setSeries] = useState('zones');
  const [data, setData] = useState(null);
  const [error, setError] = useState('');
  const [busy, setBusy] = useState(false);

  useEffect(() => {
    let live = true;
    setBusy(true);
    setError('');
    reportsApi.analytics({ months, ...(includeSamples ? { include_samples: 'true' } : {}) })
      .then((d) => { if (live) setData(d); })
      .catch((err) => {
        if (!live) return;
        setError(err?.status === 403
          ? 'You do not have permission to view analytics.'
          : 'Analytics could not be loaded right now. Please try again later.');
      })
      .finally(() => { if (live) setBusy(false); });
    return () => { live = false; };
  }, [months, includeSamples]);

  const current = SERIES.find((s) => s.key === series);
  const points = useMemo(
    () => (data?.monthly || []).map((m) => ({ label: monthLabel(m.month), value: m[series] })),
    [data, series],
  );

  const criteria = `months=${months}${includeSamples ? ' samples=included' : ''}`;
  async function log(via) {
    try { await reportsApi.printed('analytics', criteria, via); } catch { /* export anyway */ }
  }
  async function exportCsv() {
    await log('csv');
    downloadCsv(csvFilename('analytics'), analyticsCsv(data));
  }
  async function print(via) {
    await log(via);
    window.print();
  }

  const k = data?.kpis;

  return (
    <>

        <div className="db-card an-toolbar db-no-print">
          <div className="an-seg" role="group" aria-label="Period">
            {WINDOWS.map((w) => (
              <button
                key={w}
                type="button"
                className={months === w ? 'is-active' : ''}
                aria-pressed={months === w}
                onClick={() => setMonths(w)}
                disabled={busy}
              >
                {w} months
              </button>
            ))}
          </div>
          <label className="db-report-check">
            <input type="checkbox" checked={includeSamples} onChange={(e) => setIncludeSamples(e.target.checked)} />
            Include sample data
          </label>
          <div className="db-btn-row an-exports">
            <button type="button" className="db-btn db-btn-outline db-btn-sm" onClick={exportCsv} disabled={!data || busy}>
              Download CSV
            </button>
            <button
              type="button"
              className="db-btn db-btn-outline db-btn-sm"
              onClick={() => print('pdf')}
              disabled={!data || busy}
              title='Opens the print dialog. Choose "Save as PDF" as the printer.'
            >
              Save as PDF
            </button>
            <button type="button" className="db-btn db-btn-outline db-btn-sm" onClick={() => print('print')} disabled={!data || busy}>
              Print
            </button>
          </div>
        </div>

        {error && <div className="db-card"><p className="db-error" role="alert">{error}</p></div>}
        {!data && !error && <div className="db-card"><p className="db-empty">Loading analytics…</p></div>}

        {data && (
          <div className={`an-body ${busy ? 'is-busy' : ''}`}>
            <p className="an-period">
              Last {data.months} months, from {new Date(data.since).toLocaleDateString(undefined, { month: 'long', year: 'numeric' })}.
              {' '}Generated by {data.generated_by}, {new Date(data.generated_at).toLocaleString()}.
            </p>
            {data.includes_samples && (
              <p className="db-error" role="status">
                <strong>Includes sample data.</strong> These figures count seeded test rows, so they are not an official record.
              </p>
            )}

            <div className="db-stats">
              <Stat value={k.active_zones_now} label="Active zones now" />
              <Stat value={k.zones_published} label="Zones published"
                hint={k.zones_retracted ? `${k.zones_retracted} more withdrawn as errors` : null} />
              <Stat value={k.alerts_issued} label="Alerts issued" hint={`${k.extreme_alerts} Extreme`} />
              <Stat value={k.incidents_submitted} label="Incident reports"
                hint={k.incidents_pending ? `${k.incidents_pending} still pending` : 'none pending'} />
              <Stat value={k.recorded_events} label="Recorded hazard events" />
            </div>

            <div className="db-card">
              <h2>Response</h2>
              <p className="db-card-sub">How quickly alerts were read and reports were reviewed. Medians, so one slow case does not skew them.</p>
              <div className="an-response">
                <div>
                  <span className="an-big">{percent(k.read_rate)}</span>
                  <span>of alert notices opened</span>
                  <small>{k.notices_read} of {k.notices_sent} sent</small>
                </div>
                <div>
                  <span className="an-big">{duration(k.median_minutes_to_read)}</span>
                  <span>to open an alert</span>
                  <small>from when it was sent</small>
                </div>
                <div>
                  <span className="an-big">{percent(k.review_rate)}</span>
                  <span>of incident reports reviewed</span>
                  <small>{k.incidents_validated} validated, {k.incidents_rejected} rejected</small>
                </div>
                <div>
                  <span className="an-big">{duration(k.median_minutes_to_review)}</span>
                  <span>to review a report</span>
                  <small>from submission to decision</small>
                </div>
                <div>
                  <span className="an-big">{duration(k.median_minutes_zone_active)}</span>
                  <span>a zone stayed active</span>
                  <small>from publishing to resolved</small>
                </div>
              </div>
            </div>

            <div className="db-card">
              <div className="an-card-head">
                <div>
                  <h2>Month by month</h2>
                  <p className="db-card-sub">{current.label}, per month.</p>
                </div>
                <div className="an-seg an-seg-sm db-no-print" role="group" aria-label="Series">
                  {SERIES.map((s) => (
                    <button
                      key={s.key}
                      type="button"
                      className={series === s.key ? 'is-active' : ''}
                      aria-pressed={series === s.key}
                      onClick={() => setSeries(s.key)}
                    >
                      {s.label}
                    </button>
                  ))}
                </div>
              </div>
              <TrendLine points={points} color={current.color} />
              <details className="an-table-wrap">
                <summary>Show the numbers</summary>
                <table className="db-table">
                  <thead>
                    <tr><th>Month</th>{SERIES.map((s) => <th key={s.key}>{s.label}</th>)}</tr>
                  </thead>
                  <tbody>
                    {data.monthly.map((m) => (
                      <tr key={m.month}>
                        <td>{monthLabel(m.month)}</td>
                        {SERIES.map((s) => <td key={s.key}>{m[s.key]}</td>)}
                      </tr>
                    ))}
                  </tbody>
                </table>
              </details>
            </div>

            <div className="db-grid-2 an-grid">
              <div className="db-card">
                <h2>Zones by hazard type</h2>
                <CategoryBars
                  rows={toRows(data.zones_by_type, 'hazard_type__name', undefined, (r) => hazardSeriesColor(r.hazard_type__name))}
                  valueHead="Zones"
                  empty="No zones in this period."
                />
              </div>
              <div className="db-card">
                <h2>Zones by severity</h2>
                <CategoryBars
                  rows={toRows(data.zones_by_severity, 'severity', (r) => SEVERITY_LABEL[r.severity] || r.severity, (r) => severitySeriesColor(r.severity))}
                  valueHead="Zones"
                  empty="No zones in this period."
                />
              </div>
              <div className="db-card">
                <h2>Barangays with the most zones</h2>
                <CategoryBars rows={toRows(data.zones_by_barangay, 'barangay__name')} valueHead="Zones" empty="No zones in this period." />
              </div>
              <div className="db-card">
                <h2>Barangays reporting the most incidents</h2>
                <CategoryBars rows={toRows(data.incidents_by_barangay, 'barangay__name')} valueHead="Reports" empty="No incident reports in this period." />
              </div>
            </div>

            <div className="db-card">
              <h2>Likely next month</h2>
              <p className="db-card-sub">
                Barangays that next month has tended to hit in past years, from the historical record.
              </p>
              <BarangayLikelihood compact limit={5} />
            </div>
          </div>
        )}
    </>
  );
}
