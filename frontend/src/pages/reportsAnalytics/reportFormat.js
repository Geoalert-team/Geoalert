// Numbers, shares and CSV files for Reports & Analytics, kept apart from the
// screens so the file always matches what is on screen and can be tested.
import { toCsv } from '../../utils/csv';
import { SEVERITY_LABEL } from '../../utils/severity';
import { duration } from '../../components/Analytics/measures';

export const IMPACT = [
  { key: 'deaths', label: 'Deaths', csv: 'Deaths' },
  { key: 'injured', label: 'Injured', csv: 'Injured' },
  { key: 'families_affected', label: 'Families affected', csv: 'Families affected' },
  { key: 'persons_affected', label: 'Persons affected', csv: 'Persons affected' },
  { key: 'structures_affected', label: 'Structures affected', csv: 'Structures affected' },
  { key: 'damage_cost', label: 'Damage cost', csv: 'Damage cost (PHP)', money: true },
  // The BFP log's total of people hurt or killed where its split cells are blank or fewer
  { key: 'unsplit_casualties', label: 'Hurt or killed, not split', csv: 'Hurt or killed, not split (BFP total)' },
];

export const num = (v) => (v === null || v === undefined ? '—' : Number(v).toLocaleString());
export const peso = (v) => (v === null || v === undefined ? '—'
  : `₱${Number(v).toLocaleString(undefined, { maximumFractionDigits: 0 })}`);
export const figure = (item, v) => (item.money ? peso(v) : num(v));

/** "recorded on 2 of 4 records" or "not recorded in these 4 records" */
export function recordedText(m) {
  if (!m.of) return 'no records';
  return m.recorded_on ? `recorded on ${m.recorded_on} of ${m.of} records` : `not recorded in these ${m.of} records`;
}

/** [{ label, count, share }], share of the rows' own total (null when it is 0). */
export function withShares(rows = [], labelOf, countOf = (r) => r.count) {
  const total = rows.reduce((sum, r) => sum + (countOf(r) || 0), 0);
  return rows.map((r) => {
    const count = countOf(r) || 0;
    return { label: labelOf(r), count, share: total ? count / total : null };
  });
}

export function formatShare(share) {
  if (share === null || share === undefined) return '—';
  if (share > 0 && share < 0.005) return '<1%';
  return `${Math.round(share * 100)}%`;
}

/** A figure of the answer, read as not recorded when an older answer lacks it. */
export const impactOf = (s, key) => (s.impact && s.impact[key]) || { value: null, recorded_on: 0, of: s.events };

const meta = (title, answer, words) => [
  ['Report', title],
  ['Filters', words],
  ['Generated by', answer.generated_by || ''],
  ['Generated at', answer.generated_at ? new Date(answer.generated_at).toLocaleString() : ''],
];
const cell = (v) => (v === null || v === undefined ? '' : v);
const impactRow = (r) => IMPACT.map((i) => cell(r[i.key]));

/** The Summary section (the Hazard Summary report) as CSV. */
export function summaryCsv(s, words) {
  const counted = (rows, head) => ({ header: [head, 'Records'], rows: rows.map((r) => [r.label, r.count]) });
  const sections = [
    { title: 'What GeoAlert holds: archive', header: ['Hazard', 'Records', 'First', 'Last'],
      rows: s.holdings.archive.map((a) => [a.hazard, a.records, a.first, a.last]) },
    { title: 'What GeoAlert holds: its own records', header: ['Kind', 'Count', 'First'], rows: [
      ['Hazard zones', s.holdings.zones.count, cell(s.holdings.zones.first)],
      ['Alerts', s.holdings.alerts.count, cell(s.holdings.alerts.first)],
      ['Alert notices', s.holdings.notices.count, ''],
      ['Incident reports', s.holdings.incident_reports.count, cell(s.holdings.incident_reports.first)],
      ['Barangays', s.holdings.barangays, ''],
      ['Puroks', s.holdings.puroks, ''],
    ] },
    { title: 'Impact', header: ['Measure', 'Value', 'Records carrying it', 'Records'], rows: [
      ['Events', s.events, s.events, s.events],
      ...IMPACT.map((i) => { const m = impactOf(s, i.key); return [i.csv, cell(m.value), m.recorded_on, m.of]; }),
      ['Total displaced', 'Not recorded'],
    ] },
    { title: 'By hazard type', header: ['Hazard type', 'Events', ...IMPACT.map((i) => i.csv)],
      rows: s.by_hazard.map((r) => [r.hazard, r.events, ...impactRow(r)]) },
    { title: 'By barangay', header: ['Barangay', 'Events', 'Share', ...IMPACT.map((i) => i.csv)],
      rows: s.by_barangay.map((r) => [r.name, r.events, formatShare(s.events ? r.events / s.events : null), ...impactRow(r)]) },
  ];
  if (s.by_purok.length) {
    sections.push({ title: 'By purok', header: ['Purok', 'Events'], rows: s.by_purok.map((p) => [p.name, p.events]) });
  }
  sections.push({ title: 'Severity', header: ['Severity', 'Events', 'Share'],
    rows: withShares(s.severity, (r) => SEVERITY_LABEL[r.severity] || r.severity).map((r) => [r.label, r.count, formatShare(r.share)]) });
  if (s.fire) {
    sections.push({ title: 'Fires by property category', ...counted(s.fire.property_category, 'Property category') });
    sections.push({ title: 'Fires by alarm level', ...counted(s.fire.alarm_level, 'Alarm level') });
  }
  if (s.flood_landslide) {
    sections.push({ title: 'Floods and landslides by sub-category', ...counted(s.flood_landslide.subcategory, 'Sub-category') });
    sections.push({ title: 'Floods and landslides by cause', ...counted(s.flood_landslide.cause, 'Cause') });
  }
  sections.push({ title: 'Data completeness', header: ['Records', 'Count', 'Of', 'Share'],
    rows: s.completeness.map((c) => [c.label, c.count, c.of, formatShare(c.of ? c.count / c.of : null)]) });
  return toCsv(sections, meta('Hazard Summary', s, words));
}

const pct = (share) => (share === null || share === undefined ? '' : Math.round(share * 100));

/** The Operations section (the Response Status report) as CSV. */
export function operationsCsv(a, words) {
  const k = a.kpis;
  const z = a.zones_by_status || {};
  return toCsv([
    { title: 'Hazard zones', header: ['Measure', 'Value'], rows: [
      ['Published in the period', k.zones_published], ['Active now (any period)', k.active_zones_now],
      ['Still active', z.Active], ['Resolved', z.Resolved], ['Archived', z.Archived],
      ['Withdrawn as published in error', z.Retracted],
      ['Median time a zone stayed active', duration(k.median_minutes_zone_active)],
    ] },
    { title: 'Alerts', header: ['Measure', 'Value'], rows: [
      ['Alerts issued', k.alerts_issued], ['Extreme alerts', k.extreme_alerts],
      ['Alert notices sent', k.notices_sent], ['Alert notices opened', k.notices_read],
      ['Alert notices opened (%)', pct(k.read_rate)], ['Median time to open an alert', duration(k.median_minutes_to_read)],
    ] },
    { title: 'Incident reports', header: ['Measure', 'Value'], rows: [
      ['Submitted', k.incidents_submitted], ['Pending', k.incidents_pending], ['Validated', k.incidents_validated],
      ['Rejected', k.incidents_rejected], ['Reviewed (%)', pct(k.review_rate)],
      ['Median time to review a report', duration(k.median_minutes_to_review)],
    ] },
    { title: 'Zones by hazard type', header: ['Hazard type', 'Zones'],
      rows: (a.zones_by_type || []).map((r) => [r.hazard_type__name || 'Unspecified', r.count]) },
    { title: 'Zones by severity', header: ['Severity', 'Zones'],
      rows: (a.zones_by_severity || []).map((r) => [SEVERITY_LABEL[r.severity] || r.severity, r.count]) },
    { title: 'Barangay activity', header: ['Barangay', 'Zones', 'Incident reports'],
      rows: (a.barangays || []).map((r) => [r.barangay, r.zones, r.incidents]) },
  ], meta('Response Status', a, words));
}
