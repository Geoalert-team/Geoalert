import React from 'react';
import ExportMenu from '../../components/Analytics/ExportMenu';
import { reportsApi } from '../../api/reportApi';
import { csvFilename, downloadCsv } from '../../utils/csv';
import { answerWords } from './filters';

/**
 * A Reports & Analytics section laid out as a document: office, title, the
 * filters it was made with (read from the answer itself, so a file never
 * describes filters it does not hold), who generated it and when, and its
 * export. Every export is written to the audit log first and is never
 * blocked by a failed log; export waits while figures load.
 *
 * Props: report ('hazard-summary' | 'response-status' | 'models'), title,
 * file (CSV name), answer, state ({status, error}), csv(answer, words) | null,
 * note (a line under the title), children (the figures).
 */
export default function SectionFrame({ report, title, file, answer, state, csv, note, children }) {
  const { words, criteria } = answerWords(answer);
  const loading = state && state.status === 'loading';

  async function exportAs(via) {
    try {
      await reportsApi.printed(report, criteria, via);
    } catch {
      // export anyway
    }
    if (via === 'csv') downloadCsv(csvFilename(file), csv(answer, words));
    else window.print();
  }

  return (
    <article className="ra-doc" aria-busy={loading || undefined}>
      <header className="ra-doc-head">
        <div>
          <p className="ra-doc-office">GeoAlert Talisay · City DRRMO</p>
          <h2>{title}</h2>
          {words && <p className="ra-doc-criteria">{words}</p>}
          {note && <p className="ra-doc-meta">{note}</p>}
          {answer?.generated_by && (
            <p className="ra-doc-meta">
              Generated by {answer.generated_by}
              {answer.generated_at && ` on ${new Date(answer.generated_at).toLocaleString()}`}
            </p>
          )}
        </div>
        <ExportMenu onExport={exportAs} disabled={loading || (csv && !answer)}
          vias={csv ? ['csv', 'pdf', 'print'] : ['pdf', 'print']} />
      </header>

      {state?.status === 'loading' && !answer && <p className="ra-state" role="status">Loading the figures…</p>}
      {state?.status === 'error' && <p className="db-error" role="alert">{state.error}</p>}
      {(answer || !state) && <div className={loading ? 'ra-refreshing' : ''}>{children}</div>}
    </article>
  );
}
